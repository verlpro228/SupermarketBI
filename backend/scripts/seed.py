PRODUCTS_EXTRA = [
    (f"691{index:010d}", name, category, spec, unit, purchase, sale, safe, shelf)
    for index, (name, category, spec, unit, purchase, sale, safe, shelf) in enumerate(
        _EXTRA_PRODUCTS_RAW, start=1
    )
]


def main() -> None:
    db = SessionLocal()
    try:
        for item in USERS:
            exists = db.scalar(select(User).where(User.username == item["username"]))
            if exists:
                print(f"用户已存在，跳过：{item['username']}")
                continue
            db.add(
                User(
                    username=item["username"],
                    password_hash=hash_password(item["password"]),
                    real_name=item["real_name"],
                    role=item["role"],
                    status=1,
                )
            )
            print(f"创建用户：{item['username']} / {item['password']}")

        for name, sort_order in CATEGORIES:
            exists = db.scalar(select(Category).where(Category.name == name))
            if exists:
                continue
            db.add(Category(name=name, sort_order=sort_order, status=1))
        db.flush()

        category_map = {c.name: c.id for c in db.scalars(select(Category)).all()}

        for (
            barcode,
            name,
            category_name,
            spec,
            unit,
            purchase_price,
            sale_price,
            safe_stock,
            shelf_life_days,
        ) in PRODUCTS + PRODUCTS_EXTRA:
            exists = db.scalar(select(Product).where(Product.barcode == barcode))
            if exists:
                continue
            db.add(
                Product(
                    barcode=barcode,
                    name=name,
                    category_id=category_map[category_name],
                    spec=spec,
                    unit=unit,
                    purchase_price=purchase_price,
                    sale_price=sale_price,
                    safe_stock=safe_stock,
                    shelf_life_days=shelf_life_days,
                    status=1,
                )
            )

        for key, value, desc in [
            ("expiry_urgent_days", "7", "临期-紧急分档阈值（剩余天数）"),
            ("expiry_warning_days", "30", "临期-预警分档阈值（剩余天数）"),
        ]:
            if not db.scalar(select(SysConfig).where(SysConfig.config_key == key)):
                db.add(SysConfig(config_key=key, config_value=value, description=desc))

        db.commit()
        print("基础数据初始化完成")

        print("开始生成演示业务数据...")
        generate_demo_data(db)
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()
